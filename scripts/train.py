#!/usr/bin/env python3
"""Fit a small TF-IDF example retrieval model, not a generative language model."""
import collections
import hashlib
import json
import math
import re
import unicodedata
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def tokens(text):
    text = unicodedata.normalize('NFKC', text).lower()
    out = re.findall(r'[a-z0-9]+', text)
    for run in re.findall(r'[\u3400-\u9fff]+', text):
        out.extend(run)
        out.extend(run[i:i+2] for i in range(len(run)-1))
    return out

def main():
    path = ROOT / 'training/corpus.json'
    corpus = json.loads(path.read_text())
    if not corpus or len({r['id'] for r in corpus}) != len(corpus):
        raise ValueError('Missing corpus or duplicate intent ID')
    examples = []
    for row in corpus:
        if not row['answer'].strip() or not row['questions']:
            raise ValueError('Every intent needs questions and an answer')
        for question in row['questions']:
            terms = collections.Counter(tokens(question))
            if not terms: raise ValueError('Empty example')
            examples.append((row['id'], terms))
    df = collections.Counter()
    for _, terms in examples: df.update(terms.keys())
    idf = {term: math.log((1 + len(examples))/(1 + freq)) + 1 for term,freq in sorted(df.items())}
    vectors = []
    for ident, counts in examples:
        vector = {term:(1 + math.log(count))*idf[term] for term,count in counts.items()}
        norm = math.sqrt(sum(v*v for v in vector.values()))
        vectors.append({'id':ident,'v':{t:round(v/norm,8) for t,v in vector.items()}})
    model = {'version':1,'kind':'tfidf-example-retrieval','corpusSha256':hashlib.sha256(path.read_bytes()).hexdigest(),
             'threshold':0.46,'idf':idf,'examples':vectors,
             'intents':{r['id']:{'answer':r['answer'],'suggestions':r.get('suggestions',[]),'anchors':r['anchors']} for r in corpus}}
    site = ROOT / 'src' if (ROOT / 'src/index.html').is_file() else ROOT
    (site/'model.js').write_text('/* Generated by scripts/train.py; public authored corpus only. */\n'
        +'globalThis.FREEFORAI_MODEL = '+json.dumps(model,ensure_ascii=False,separators=(',',':'))+';\n')
    print(f'Trained {len(corpus)} intents / {len(examples)} examples / {len(idf)} terms (TF-IDF retrieval).')
if __name__ == '__main__': main()
